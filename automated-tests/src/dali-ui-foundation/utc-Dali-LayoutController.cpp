// The end-to-end geometry of the same shape at a non-unit scale: a FIXED root with a
// WRAP_CONTENT boundary child that wraps a 90 wide grandchild. Every extent on the path
// (the root's own visual size, the extent the boundary child is handed, and the child's
// wrapped content) is in visual units, so the child settles at 90 * 2.
//
// Unlike the two tests above this one does NOT discriminate the FIXED-branch conversion,
// and deliberately so: it is the geometry regression guard for the shape the conversion
// touches. A FIXED root's own size comes from its requested size rather than from the
// constraint, and a boundary child is re-measured by its own root pass from the parent's
// (already visual) actor SIZE, so the constraint the root's producer is run at -- what the
// two tests above assert directly -- is not observable in the settled geometry here.
int UtcDaliLayoutControllerFixedRootStandaloneChildGetsFullExtentP(void)
{
  UiTestApplication application;
  tet_infoline("A FIXED-size root hands its boundary child the full visual extent");

  const float originalScale = UiScaleManager::Get().GetScale();
  UiScaleManager::Get().SetScale(2.0f);

  Window window = application.GetWindow();

  View root = View::New();
  root.SetRequestedWidth(100.0f);
  root.SetRequestedHeight(80.0f);
  window.Add(root);

  View standalone = View::New();
  standalone.SetLayoutMode(LayoutMode::STANDALONE);
  standalone.SetRequestedWidth(WRAP_CONTENT);
  standalone.SetMaximumWidth(1000.0f);
  root.Add(standalone);

  View grandChild = View::New();
  grandChild.SetRequestedWidth(90.0f);
  standalone.Add(grandChild);

  application.SendNotification();
  application.Render();

  // 90 natural content at scale 2, and a boundary child that wraps it.
  DALI_TEST_EQUALS(standalone.GetProperty<float>(Actor::Property::SIZE_WIDTH), 180.0f, TEST_LOCATION);

  UiScaleManager::Get().SetScale(originalScale);
  END_TEST;
}

// ─── Exception safety of one processing batch ─────────────────────────────
//
// Placed LAST in this file on purpose: it deliberately unwinds a Dali::DaliException
// out of a layout pass. The pass is driven through the MANUAL entry point
// (LayoutController::ProcessLayouts) rather than SendNotification, because
// Core::ProcessEvents sets its re-entrancy latch without RAII: an exception escaping it
// would leave that Core refusing every later ProcessEvents call, and the retry this test
// has to observe could never run.
namespace
{
int  gThrowingMeasureCount = 0;
int  gExceptionTargetCount = 0;
bool gThrowingMeasureArmed = false;

// Throws once, and only while armed. DALI_ASSERT_ALWAYS raises exactly this type, so
// this stands in for any assertion firing inside a producer.
MeasuredSize ThrowWhenArmedMeasure(View, float, float)
{
  ++gThrowingMeasureCount;
  if(gThrowingMeasureArmed)
  {
    gThrowingMeasureArmed = false;
    throw Dali::DaliException("utc", "injected");
  }
  return MeasuredSize(200.0f, 100.0f);
}

MeasuredSize ExceptionTargetMeasure(View, float, float)
{
  ++gExceptionTargetCount;
  return MeasuredSize(100.0f, 50.0f);
}

// Arms the throw and re-dirties both roots from inside the LayoutFinished emit, exactly
// once. Invalidating from a slot is PARKED: the work lands in the pending set but arms no
// idle wake, which is what leaves mIdleWakeArmed false and makes the no-wake assertion
// below observable rather than vacuous.
struct ArmThrowAndInvalidateOnce
{
  ArmThrowAndInvalidateOnce(int& count, View source, View target)
  : count(count),
    source(source),
    target(target)
  {
  }
  void operator()(Window)
  {
    ++count;
    if(count == 1)
    {
      gThrowingMeasureArmed = true;
      source.InvalidateMeasure();
      target.InvalidateMeasure();
    }
  }
  int& count;
  View source;
  View target;
};
} // namespace

// ProcessLayouts swaps the pending set into a stack-local vector, so between the swap
// and the end of the loop the member set names NONE of the roots still to run. An
// exception out of a producer destroys that vector and used to lose them all: the
// second root's layout would simply never run again, and nothing would re-register it.
//
// Non-vacuity (verified by mutation): disarming PendingBatchRollbackScope leaves the
// target's producer count frozen and the source is never retried either.
int UtcDaliLayoutControllerBatchSurvivesProducerExceptionP(void)
{
  UiTestApplication application;
  Window            window = application.GetWindow();
  tet_infoline("A producer exception does not lose the rest of the pending batch");

  gThrowingMeasureCount = 0;
  gExceptionTargetCount = 0;
  gThrowingMeasureArmed = false;

  // Directly under the Window (depth 1), so the depth sort runs it FIRST.
  View source = View::New();
  source.SetRequestedWidth(200.0f);
  source.SetRequestedHeight(100.0f);
  source.SetMeasureCallback(MeasureCallback::New(&ThrowWhenArmedMeasure));

  // Under a non-View actor (depth 2): an independent layout root that the sort places
  // after `source`, so it is still queued when `source` throws.
  Actor targetHost = Actor::New();
  View  target     = View::New();
  target.SetRequestedWidth(100.0f);
  target.SetRequestedHeight(50.0f);
  target.SetMeasureCallback(MeasureCallback::New(&ExceptionTargetMeasure));

  int                       emitCount = 0;
  ArmThrowAndInvalidateOnce rearm(emitCount, source, target);
  LayoutController::Get(window).LayoutFinishedSignal().Connect(&application, rearm);

  window.Add(source);
  window.Add(targetHost);
  targetHost.Add(target);

  // A normal batch first. It completes, emits once, and the slot then arms the throw and
  // parks a fresh dirty state on both roots without requesting a wake.
  SendRequestedProcessEvents(application);
  DALI_TEST_EQUALS(emitCount, 1, TEST_LOCATION);
  DALI_TEST_EQUALS(gThrowingMeasureCount, 1, TEST_LOCATION);
  DALI_TEST_EQUALS(gExceptionTargetCount, 1, TEST_LOCATION);
  DALI_TEST_CHECK(!WasProcessEventsOnIdleRequested(application));

  // 1. The parked batch runs and the FIRST root's producer throws out of it.
  bool caught = false;
  try
  {
    LayoutController::Get(window).ProcessLayouts();
  }
  catch(const Dali::DaliException&)
  {
    caught = true;
  }
  DALI_TEST_CHECK(caught);
  DALI_TEST_EQUALS(gThrowingMeasureCount, 2, TEST_LOCATION);
  DALI_TEST_EQUALS(gExceptionTargetCount, 1, TEST_LOCATION); // never got its turn

  // 2. The rollback re-registered both roots WITHOUT arming an idle wake: a wake here
  //    would re-drive the producer that just threw, at full main-loop rate. No wake was
  //    outstanding going in, so this really does observe the rollback's own choice.
  DALI_TEST_CHECK(!WasProcessEventsOnIdleRequested(application));
  DALI_TEST_EQUALS(emitCount, 1, TEST_LOCATION);

  // 3. The next independently driven cycle drains the restored batch. The target runs
  //    for the first time since the abort, and the source retries.
  SendIndependentProcessEvents(application);
  DALI_TEST_EQUALS(gExceptionTargetCount, 2, TEST_LOCATION);
  DALI_TEST_EQUALS(gThrowingMeasureCount, 3, TEST_LOCATION);

  // 4. ...and that pass completed, so LayoutFinished emitted again.
  DALI_TEST_EQUALS(emitCount, 2, TEST_LOCATION);

  // Steady state: nothing re-schedules itself.
  SendIndependentProcessEvents(application);
  DALI_TEST_EQUALS(gExceptionTargetCount, 2, TEST_LOCATION);
  DALI_TEST_EQUALS(gThrowingMeasureCount, 3, TEST_LOCATION);
  DALI_TEST_EQUALS(emitCount, 2, TEST_LOCATION);

  END_TEST;
}

// A batch that throws keeps the View snapshots of the layout roots it had already
// completed -- the next automatic cycle delivers them -- but earns no Window notification
// of its own. Driven through the manual entry point for the same reason as the test
// above: Core::ProcessEvents' re-entrancy latch is not RAII.
int UtcDaliLayoutControllerFailedBatchKeepsCompletedRootSnapshotsP(void)
{
  UiTestApplication application;
  Window            window = application.GetWindow();
  tet_infoline("A failed batch keeps the snapshots of its completed roots but earns no Window notification");

  gThrowingMeasureCount = 0;
  gThrowingMeasureArmed = false;

  // Directly under the Window (depth 1), so the depth sort runs it FIRST.
  View first = View::New();
  first.SetRequestedWidth(100.0f);
  first.SetRequestedHeight(60.0f);

  // Under a non-View actor (depth 2): an independent layout root that runs after `first`.
  Actor host     = Actor::New();
  View  throwing = View::New();
  throwing.SetRequestedWidth(80.0f);
  throwing.SetRequestedHeight(50.0f);
  throwing.SetMeasureCallback(MeasureCallback::New(&ThrowWhenArmedMeasure));

  LayoutController&  controller = LayoutController::Get(window);
  std::vector<float> widths;
  int                finishes = 0;
  first.LayoutFinishedSignal().Connect(&application, [&](View, LayoutRect bounds)
  { widths.push_back(bounds.width); });
  controller.LayoutFinishedSignal().Connect(&application, CountLayoutFinishedFunctor(finishes));

  window.Add(first);
  window.Add(host);
  host.Add(throwing);

  SendRequestedProcessEvents(application);
  DALI_TEST_EQUALS(widths.size(), 1u, TEST_LOCATION);
  if(widths.size() == 1u)
  {
    DALI_TEST_EQUALS(widths[0], 100.0f, 0.01f, TEST_LOCATION);
  }
  DALI_TEST_EQUALS(finishes, 1, TEST_LOCATION);
  DALI_TEST_EQUALS(gThrowingMeasureCount, 1, TEST_LOCATION);

  // `first` completes its pass at 140, then `throwing` throws out of the same batch.
  first.SetRequestedWidth(140.0f);
  throwing.InvalidateMeasure();
  gThrowingMeasureArmed = true;
  bool caught           = false;
  try
  {
    controller.ProcessLayouts();
  }
  catch(const Dali::DaliException&)
  {
    caught = true;
  }
  DALI_TEST_CHECK(caught);
  DALI_TEST_EQUALS(gThrowingMeasureCount, 2, TEST_LOCATION);
  DALI_TEST_EQUALS(first.GetProperty<float>(Actor::Property::SIZE_WIDTH), 140.0f, 0.01f, TEST_LOCATION);
  DALI_TEST_EQUALS(widths.size(), 1u, TEST_LOCATION);
  DALI_TEST_EQUALS(finishes, 1, TEST_LOCATION);

  // Drop the throwing root: leaving the scene unregisters the root the rollback restored.
  host.Remove(throwing);
  throwing.Reset();
  window.Remove(host);
  host.Reset();

  // Nothing is pending, but the automatic pre-process promotes the snapshot the failed
  // batch recorded for `first`; that batch never set the Window flag.
  application.SendNotification();
  DALI_TEST_EQUALS(widths.size(), 2u, TEST_LOCATION);
  if(widths.size() == 2u)
  {
    DALI_TEST_EQUALS(widths[0], 100.0f, 0.01f, TEST_LOCATION);
    DALI_TEST_EQUALS(widths[1], 140.0f, 0.01f, TEST_LOCATION);
  }
  DALI_TEST_EQUALS(finishes, 1, TEST_LOCATION);

  application.SendNotification();
  DALI_TEST_EQUALS(widths.size(), 2u, TEST_LOCATION);
  DALI_TEST_EQUALS(finishes, 1, TEST_LOCATION);
  END_TEST;
}

// The documented contract is a positive, finite, NORMAL scale. A subnormal scale is not
// a usable display scale and would make the layout's reciprocal overflow, so it is
// rejected together with the non-finite values rather than clamped.
int UtcDaliUiScaleManagerSetScaleSubnormalRejectedN(void)
{
  UiTestApplication application;
  tet_infoline("A subnormal or non-finite UI scale is rejected, leaving the previous scale in place");

  const float originalScale = UiScaleManager::Get().GetScale();

  UiScaleManager::Get().SetScale(1.0f);
  DALI_TEST_EQUALS(UiScaleManager::Get().GetScale(), 1.0f, TEST_LOCATION);

  UiScaleManager::Get().SetScale(std::numeric_limits<float>::denorm_min());
  DALI_TEST_EQUALS(UiScaleManager::Get().GetScale(), 1.0f, TEST_LOCATION);

  UiScaleManager::Get().SetScale(std::numeric_limits<float>::quiet_NaN());
  DALI_TEST_EQUALS(UiScaleManager::Get().GetScale(), 1.0f, TEST_LOCATION);

  UiScaleManager::Get().SetScale(originalScale);
  END_TEST;
}
