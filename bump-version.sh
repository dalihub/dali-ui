#!/bin/bash
set -euo pipefail

REPO_DIR=$(dirname "$(readlink -f "$0")")
VERSION_FILE="$REPO_DIR/version.txt"

COMPONENT=${1-}
if (( $# != 1 )) || [[ ! $COMPONENT =~ ^(major|minor|patch)$ ]]; then
  echo "Usage: $0 {major|minor|patch}" >&2
  exit 1
fi

if ! BASE_VERSION=$(grep -Ev '^[[:space:]]*(#|$)' "$VERSION_FILE") ||
   [[ ! $BASE_VERSION =~ ^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$ ]]; then
  echo 'version.txt must contain one X.Y.Z version line.' >&2
  exit 1
fi

IFS=. read -r major minor patch <<< "$BASE_VERSION"
printf -v CURRENT '%d' "${!COMPONENT}"
NEXT=$((CURRENT + 1))
if (( NEXT <= CURRENT )); then
  echo "Cannot increment $COMPONENT version beyond $CURRENT." >&2
  exit 1
fi
printf -v "$COMPONENT" '%d' "$NEXT"

case $COMPONENT in
  major) minor=0; patch=0 ;;
  minor) patch=0 ;;
esac

TEMP_DIR=$(mktemp -d "$REPO_DIR/.versionup.XXXXXX")
trap 'rm -rf -- "$TEMP_DIR"' EXIT
cp -p -- "$VERSION_FILE" "$TEMP_DIR/previous"
{
  echo '# Auto-generated by bump-version.sh. Do not edit directly.'
  printf '%s.%s.%s\n' "$major" "$minor" "$patch"
} > "$TEMP_DIR/version.txt"
mv -fT -- "$TEMP_DIR/version.txt" "$VERSION_FILE"

if ! RPM_VERSION=$("$REPO_DIR/packaging/makespec.sh"); then
  if ! mv -fT -- "$TEMP_DIR/previous" "$VERSION_FILE"; then
    trap - EXIT
    echo "Could not restore version.txt. The backup is at $TEMP_DIR/previous." >&2
  fi
  exit 1
fi

printf '%s\n' "$RPM_VERSION"
