PlayerErrorInfo GetPlayerErrorInfo(int error)
{
  switch(error)
  {
    case PLAYER_ERROR_NONE:                        return {"PLAYER_ERROR_NONE", "No error"};
    case PLAYER_ERROR_OUT_OF_MEMORY:               return {"PLAYER_ERROR_OUT_OF_MEMORY", "Out of memory"};
    case PLAYER_ERROR_INVALID_PARAMETER:           return {"PLAYER_ERROR_INVALID_PARAMETER", "Invalid parameter"};
    case PLAYER_ERROR_NO_SUCH_FILE:                return {"PLAYER_ERROR_NO_SUCH_FILE", "No such file"};
    case PLAYER_ERROR_INVALID_OPERATION:           return {"PLAYER_ERROR_INVALID_OPERATION", "Invalid operation"};
    case PLAYER_ERROR_FILE_NO_SPACE_ON_DEVICE:     return {"PLAYER_ERROR_FILE_NO_SPACE_ON_DEVICE", "No space on device"};
    case PLAYER_ERROR_FEATURE_NOT_SUPPORTED_ON_DEVICE: return {"PLAYER_ERROR_FEATURE_NOT_SUPPORTED_ON_DEVICE", "Not supported feature"};
    case PLAYER_ERROR_SEEK_FAILED:                 return {"PLAYER_ERROR_SEEK_FAILED", "Seek failed"};
    case PLAYER_ERROR_INVALID_STATE:               return {"PLAYER_ERROR_INVALID_STATE", "Invalid state"};
    case PLAYER_ERROR_NOT_SUPPORTED_FILE:          return {"PLAYER_ERROR_NOT_SUPPORTED_FILE", "Not supported file"};
    case PLAYER_ERROR_INVALID_URI:                 return {"PLAYER_ERROR_INVALID_URI", "Invalid URI"};
    case PLAYER_ERROR_CONNECTION_FAILED:           return {"PLAYER_ERROR_CONNECTION_FAILED", "Connection failed"};
    case PLAYER_ERROR_RESOURCE_LIMIT:              return {"PLAYER_ERROR_RESOURCE_LIMIT", "Resource limit"};
    case PLAYER_ERROR_PERMISSION_DENIED:           return {"PLAYER_ERROR_PERMISSION_DENIED", "Permission denied"};
    case PLAYER_ERROR_SERVICE_DISCONNECTED:        return {"PLAYER_ERROR_SERVICE_DISCONNECTED", "Service disconnected"};
    case PLAYER_ERROR_NOT_SUPPORTED_VIDEO_CODEC:   return {"PLAYER_ERROR_NOT_SUPPORTED_VIDEO_CODEC", "Unsupported codec"};
    default:                                       return {"PLAYER_ERROR_UNKNOWN", "Unknown error"};
  }
}

void PrintPlayerError(const char* operation, int error)
{
  PlayerErrorInfo info = GetPlayerErrorInfo(error);
  printf("[video-view] %s failed: %s, value=%d (0x%08x), %s\n",
         operation, info.name, error, static_cast<unsigned int>(error), info.description);
}
